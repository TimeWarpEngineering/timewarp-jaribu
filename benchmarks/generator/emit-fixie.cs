#region Purpose
// Emits TimeWarp.Fixie workloads using the convention's sync and Input shapes.
#endregion

#region Design
// TimeWarp.Fixie 3.1.0 runs Setup per test and ConfigureServices once per class.
// There is no session-fixture type. The fixture workload uses ConfigureServices as
// the once-per-class hook and a static token created when the type initializes
// as the once-per-process stand-in. Helpers stay internal so discovery skips them.
#endregion

using System.Globalization;

internal static class FixieEmit
{
  internal static void Write(string directory, WorkloadSpec spec)
  {
    Directory.CreateDirectory(directory);
    EmitText.WriteProbe(directory);
    using StreamWriter writer = new(Path.Combine(directory, spec.Id + ".g.cs"), append: false);
    writer.WriteLine("// <auto-generated />");
    writer.WriteLine("#nullable enable");
    writer.WriteLine("using Microsoft.Extensions.DependencyInjection;");
    writer.WriteLine("using TimeWarp.Fixie;");
    writer.WriteLine();
    writer.WriteLine("namespace FixieBench;");
    writer.WriteLine();
    if (spec.Kind == WorkloadKind.Fixtures)
    {
      WriteSession(writer);
      for (int typeIndex = 0; typeIndex < spec.Classes; typeIndex++)
      {
        WriteFixtureClass(writer, spec, typeIndex);
      }

      return;
    }

    writer.WriteLine("public class " + ClassName(spec));
    writer.WriteLine("{");
    for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
    {
      WriteMethod(writer, spec, methodIndex);
    }

    writer.WriteLine("}");
  }

  private static string ClassName(WorkloadSpec spec) => spec.Id switch
  {
    "startup" => "StartupTests",
    "volume-1k" => "Volume1KTests",
    "volume-10k" => "Volume10KTests",
    "parameterized" => "ParameterizedTests",
    "async-1k" => "Async1KTests",
    _ => "WorkloadTests"
  };

  private static void WriteSession(StreamWriter writer)
  {
    writer.WriteLine("internal static class SessionState");
    writer.WriteLine("{");
    writer.WriteLine("  internal static readonly int Id = Interlocked.Increment(ref Created);");
    writer.WriteLine("  internal static int Created;");
    writer.WriteLine("  internal static int ClassSetups;");
    writer.WriteLine("}");
    writer.WriteLine();
  }

  private static void WriteFixtureClass(StreamWriter writer, WorkloadSpec spec, int typeIndex)
  {
    string className = EmitText.FixtureClassName(typeIndex);
    writer.WriteLine("public class " + className);
    writer.WriteLine("{");
    writer.WriteLine("  private static int Ready;");
    writer.WriteLine();
    writer.WriteLine("  public static void ConfigureServices(IServiceCollection services)");
    writer.WriteLine("  {");
    writer.WriteLine("    _ = services;");
    writer.WriteLine("    Interlocked.Increment(ref Ready);");
    writer.WriteLine("    Interlocked.Increment(ref SessionState.ClassSetups);");
    writer.WriteLine("  }");
    writer.WriteLine();
    for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
    {
      string name = EmitText.CaseName(methodIndex);
      writer.WriteLine("  public void " + name + "()");
      writer.WriteLine("  {");
      writer.WriteLine("    if (SessionState.Id < 1 || Ready < 1)");
      writer.WriteLine("    {");
      writer.WriteLine("      throw new InvalidOperationException(\"class setup did not run\");");
      writer.WriteLine("    }");
      writer.WriteLine();
      writer.WriteLine("    Bench.BenchProbe.Touch(SessionState.Id);");
      writer.WriteLine("  }");
      writer.WriteLine();
    }

    writer.WriteLine("}");
    writer.WriteLine();
  }

  private static void WriteMethod(StreamWriter writer, WorkloadSpec spec, int methodIndex)
  {
    string name = EmitText.CaseName(methodIndex);
    if (spec.Kind == WorkloadKind.Parameterized)
    {
      for (int input = 0; input < spec.Inputs; input++)
      {
        writer.WriteLine("  [Input(" + input.ToString(CultureInfo.InvariantCulture) + ")]");
      }

      writer.WriteLine("  public void " + name + "(int value)");
      writer.WriteLine("  {");
      writer.WriteLine("    Bench.BenchProbe.Touch(value);");
      writer.WriteLine("  }");
      writer.WriteLine();
      return;
    }

    if (spec.Kind == WorkloadKind.Async)
    {
      writer.WriteLine("  public async Task " + name + "()");
      writer.WriteLine("  {");
      writer.WriteLine("    Bench.BenchProbe.Touch(0);");
      writer.WriteLine("    await Task.Yield();");
      writer.WriteLine("  }");
      writer.WriteLine();
      return;
    }

    writer.WriteLine("  public void " + name + "()");
    writer.WriteLine("  {");
    writer.WriteLine("    Bench.BenchProbe.Touch(0);");
    writer.WriteLine("  }");
    writer.WriteLine();
  }
}
