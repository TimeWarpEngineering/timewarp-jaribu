#region Purpose
// Emits xUnit v3 workloads with Fact, Theory, class fixtures, and an assembly fixture.
#endregion

#region Design
// AssemblyFixture is the session hook and IClassFixture is the once-per-class hook.
// The trivial shape is a void Fact. Theories use InlineData. The async workload
// awaits Task.Yield.
#endregion

using System.Globalization;

internal static class XunitEmit
{
  internal static void Write(string directory, WorkloadSpec spec)
  {
    Directory.CreateDirectory(directory);
    EmitText.WriteProbe(directory);
    using StreamWriter writer = new(Path.Combine(directory, spec.Id + ".g.cs"), append: false);
    writer.WriteLine("// <auto-generated />");
    writer.WriteLine("#nullable enable");
    writer.WriteLine("using Xunit;");
    writer.WriteLine();
    if (spec.Kind == WorkloadKind.Fixtures)
    {
      writer.WriteLine("[assembly: AssemblyFixture(typeof(XunitBench.SessionToken))]");
      writer.WriteLine();
    }

    writer.WriteLine("namespace XunitBench;");
    writer.WriteLine();
    if (spec.Kind == WorkloadKind.Fixtures)
    {
      WriteFixtures(writer, spec);
      return;
    }

    writer.WriteLine("public class " + ClassName(spec));
    writer.WriteLine("{");
    for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
    {
      WriteMethod(writer, spec, methodIndex);
    }

    writer.WriteLine("}");
  }

  private static string ClassName(WorkloadSpec spec) => spec.Id switch
  {
    "startup" => "StartupTests",
    "volume-1k" => "Volume1KTests",
    "volume-10k" => "Volume10KTests",
    "parameterized" => "ParameterizedTests",
    "async-1k" => "Async1KTests",
    _ => "WorkloadTests"
  };

  private static void WriteFixtures(StreamWriter writer, WorkloadSpec spec)
  {
    writer.WriteLine("public sealed class SessionToken : IAsyncLifetime, IAsyncDisposable");
    writer.WriteLine("{");
    writer.WriteLine("  public static int Created;");
    writer.WriteLine("  public int Id { get; private set; }");
    writer.WriteLine("  public ValueTask InitializeAsync()");
    writer.WriteLine("  {");
    writer.WriteLine("    Id = Interlocked.Increment(ref Created);");
    writer.WriteLine("    return ValueTask.CompletedTask;");
    writer.WriteLine("  }");
    writer.WriteLine();
    writer.WriteLine("  public ValueTask DisposeAsync() => ValueTask.CompletedTask;");
    writer.WriteLine("}");
    writer.WriteLine();
    writer.WriteLine("public sealed class ClassToken : IAsyncLifetime, IAsyncDisposable");
    writer.WriteLine("{");
    writer.WriteLine("  public static int Created;");
    writer.WriteLine("  public int Id { get; private set; }");
    writer.WriteLine("  public ValueTask InitializeAsync()");
    writer.WriteLine("  {");
    writer.WriteLine("    Id = Interlocked.Increment(ref Created);");
    writer.WriteLine("    return ValueTask.CompletedTask;");
    writer.WriteLine("  }");
    writer.WriteLine();
    writer.WriteLine("  public ValueTask DisposeAsync() => ValueTask.CompletedTask;");
    writer.WriteLine("}");
    writer.WriteLine();
    for (int typeIndex = 0; typeIndex < spec.Classes; typeIndex++)
    {
      string className = EmitText.FixtureClassName(typeIndex);
      writer.WriteLine("public sealed class " + className + " : IClassFixture<ClassToken>");
      writer.WriteLine("{");
      writer.WriteLine("  private readonly ClassToken ClassToken;");
      writer.WriteLine("  private readonly SessionToken SessionToken;");
      writer.WriteLine();
      writer.WriteLine("  public " + className + "(ClassToken classToken, SessionToken sessionToken)");
      writer.WriteLine("  {");
      writer.WriteLine("    ClassToken = classToken;");
      writer.WriteLine("    SessionToken = sessionToken;");
      writer.WriteLine("  }");
      writer.WriteLine();
      for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
      {
        string name = EmitText.CaseName(methodIndex);
        writer.WriteLine("  [Fact]");
        writer.WriteLine("  public void " + name + "()");
        writer.WriteLine("  {");
        writer.WriteLine("    if (ClassToken.Id < 1 || SessionToken.Id < 1)");
        writer.WriteLine("    {");
        writer.WriteLine("      throw new InvalidOperationException(\"fixtures were not created\");");
        writer.WriteLine("    }");
        writer.WriteLine();
        writer.WriteLine("    Bench.BenchProbe.Touch(ClassToken.Id + SessionToken.Id);");
        writer.WriteLine("  }");
        writer.WriteLine();
      }

      writer.WriteLine("}");
      writer.WriteLine();
    }
  }

  private static void WriteMethod(StreamWriter writer, WorkloadSpec spec, int methodIndex)
  {
    string name = EmitText.CaseName(methodIndex);
    if (spec.Kind == WorkloadKind.Parameterized)
    {
      writer.WriteLine("  [Theory]");
      for (int input = 0; input < spec.Inputs; input++)
      {
        writer.WriteLine("  [InlineData(" + input.ToString(CultureInfo.InvariantCulture) + ")]");
      }

      writer.WriteLine("  public void " + name + "(int value)");
      writer.WriteLine("  {");
      writer.WriteLine("    Bench.BenchProbe.Touch(value);");
      writer.WriteLine("  }");
      writer.WriteLine();
      return;
    }

    if (spec.Kind == WorkloadKind.Async)
    {
      writer.WriteLine("  [Fact]");
      writer.WriteLine("  public async Task " + name + "()");
      writer.WriteLine("  {");
      writer.WriteLine("    Bench.BenchProbe.Touch(0);");
      writer.WriteLine("    await Task.Yield();");
      writer.WriteLine("  }");
      writer.WriteLine();
      return;
    }

    writer.WriteLine("  [Fact]");
    writer.WriteLine("  public void " + name + "()");
    writer.WriteLine("  {");
    writer.WriteLine("    Bench.BenchProbe.Touch(0);");
    writer.WriteLine("  }");
    writer.WriteLine();
  }
}
