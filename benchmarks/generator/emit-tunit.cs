#region Purpose
// Emits TUnit workloads with Test, Arguments, and Before hooks.
#endregion

#region Design
// TUnit's generator requires async test methods. The trivial workload still
// awaits a completed task, which is this host's required shape. Before(Class)
// is the once-per-class hook and sets that class's Ready flag. A process-wide
// counter would let a later class pass after some other class's hook ran.
// Before(TestSession) on one type is the session hook.
#endregion

using System.Globalization;

internal static class TUnitEmit
{
  internal static void Write(string directory, WorkloadSpec spec)
  {
    Directory.CreateDirectory(directory);
    EmitText.WriteProbe(directory);
    using StreamWriter writer = new(Path.Combine(directory, spec.Id + ".g.cs"), append: false);
    writer.WriteLine("// <auto-generated />");
    writer.WriteLine("#nullable enable");
    writer.WriteLine("using TUnit.Core;");
    writer.WriteLine();
    writer.WriteLine("namespace TUnitBench;");
    writer.WriteLine();
    if (spec.Kind == WorkloadKind.Fixtures)
    {
      WriteSession(writer);
      for (int typeIndex = 0; typeIndex < spec.Classes; typeIndex++)
      {
        WriteFixtureClass(writer, spec, typeIndex);
      }

      return;
    }

    writer.WriteLine("public class " + ClassName(spec));
    writer.WriteLine("{");
    for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
    {
      WriteMethod(writer, spec, methodIndex);
    }

    writer.WriteLine("}");
  }

  private static string ClassName(WorkloadSpec spec) => spec.Id switch
  {
    "startup" => "StartupTests",
    "volume-1k" => "Volume1KTests",
    "volume-10k" => "Volume10KTests",
    "parameterized" => "ParameterizedTests",
    "async-1k" => "Async1KTests",
    _ => "WorkloadTests"
  };

  private static void WriteSession(StreamWriter writer)
  {
    writer.WriteLine("public static class SessionHooks");
    writer.WriteLine("{");
    writer.WriteLine("  public static int Created;");
    writer.WriteLine();
    writer.WriteLine("  [Before(TestSession)]");
    writer.WriteLine("  public static Task Start()");
    writer.WriteLine("  {");
    writer.WriteLine("    Interlocked.Increment(ref Created);");
    writer.WriteLine("    return Task.CompletedTask;");
    writer.WriteLine("  }");
    writer.WriteLine("}");
    writer.WriteLine();
  }

  private static void WriteFixtureClass(StreamWriter writer, WorkloadSpec spec, int typeIndex)
  {
    string className = EmitText.FixtureClassName(typeIndex);
    writer.WriteLine("public class " + className);
    writer.WriteLine("{");
    writer.WriteLine("  private static int Ready;");
    writer.WriteLine();
    writer.WriteLine("  [Before(Class)]");
    writer.WriteLine("  public static Task SetupOnce()");
    writer.WriteLine("  {");
    writer.WriteLine("    Interlocked.Increment(ref Ready);");
    writer.WriteLine("    return Task.CompletedTask;");
    writer.WriteLine("  }");
    writer.WriteLine();
    for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
    {
      string name = EmitText.CaseName(methodIndex);
      writer.WriteLine("  [Test]");
      writer.WriteLine("  public async Task " + name + "()");
      writer.WriteLine("  {");
      writer.WriteLine("    if (SessionHooks.Created < 1 || Ready < 1)");
      writer.WriteLine("    {");
      writer.WriteLine("      throw new InvalidOperationException(\"fixture hooks did not run\");");
      writer.WriteLine("    }");
      writer.WriteLine();
      writer.WriteLine("    Bench.BenchProbe.Touch(SessionHooks.Created);");
      writer.WriteLine("    await Task.CompletedTask;");
      writer.WriteLine("  }");
      writer.WriteLine();
    }

    writer.WriteLine("}");
    writer.WriteLine();
  }

  private static void WriteMethod(StreamWriter writer, WorkloadSpec spec, int methodIndex)
  {
    string name = EmitText.CaseName(methodIndex);
    writer.WriteLine("  [Test]");
    if (spec.Kind == WorkloadKind.Parameterized)
    {
      for (int input = 0; input < spec.Inputs; input++)
      {
        writer.WriteLine("  [Arguments(" + input.ToString(CultureInfo.InvariantCulture) + ")]");
      }

      writer.WriteLine("  public async Task " + name + "(int value)");
      writer.WriteLine("  {");
      writer.WriteLine("    Bench.BenchProbe.Touch(value);");
      writer.WriteLine("    await Task.CompletedTask;");
      writer.WriteLine("  }");
      writer.WriteLine();
      return;
    }

    writer.WriteLine("  public async Task " + name + "()");
    writer.WriteLine("  {");
    writer.WriteLine("    Bench.BenchProbe.Touch(0);");
    if (spec.Kind == WorkloadKind.Async)
    {
      writer.WriteLine("    await Task.Yield();");
    }
    else
    {
      writer.WriteLine("    await Task.CompletedTask;");
    }

    writer.WriteLine("  }");
    writer.WriteLine();
  }
}
