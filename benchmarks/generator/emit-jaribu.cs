#region Purpose
// Emits Jaribu workloads: Task-returning tests, Input rows, and session fixtures.
#endregion

#region Design
// Jaribu discovers public static Task methods only, so the trivial shape returns
// Task.CompletedTask and does not allocate an async state machine. Async workloads
// await Task.Yield. Fixtures use SetupOnce plus one RegisterSessionFixture call.
#endregion

using System.Globalization;

internal static class JaribuEmit
{
  internal static void Write(string directory, WorkloadSpec spec)
  {
    Directory.CreateDirectory(directory);
    EmitText.WriteProbe(directory);
    string path = Path.Combine(directory, spec.Id + ".g.cs");
    using StreamWriter writer = NewWriter(path);
    writer.WriteLine("// <auto-generated />");
    writer.WriteLine("#nullable enable");
    writer.WriteLine("using System.Runtime.CompilerServices;");
    writer.WriteLine("using TimeWarp.Jaribu;");
    writer.WriteLine("using static TimeWarp.Jaribu.TestRunner;");
    writer.WriteLine();
    writer.WriteLine("namespace Jaribu.Benchmarks;");
    writer.WriteLine();
    if (spec.Kind == WorkloadKind.Fixtures)
    {
      WriteSession(writer);
      for (int typeIndex = 0; typeIndex < spec.Classes; typeIndex++)
      {
        WriteFixtureClass(writer, spec, typeIndex);
      }

      return;
    }

    string className = ClassName(spec);
    writer.WriteLine("public sealed class " + className);
    writer.WriteLine("{");
    writer.WriteLine("  [ModuleInitializer]");
    writer.WriteLine("  internal static void Register() => RegisterTests<" + className + ">();");
    writer.WriteLine();
    for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
    {
      WriteMethod(writer, spec, methodIndex);
    }

    writer.WriteLine("}");
  }

  internal static string ClassName(WorkloadSpec spec) => spec.Id switch
  {
    "startup" => "StartupTests",
    "volume-1k" => "Volume1KTests",
    "volume-10k" => "Volume10KTests",
    "parameterized" => "ParameterizedTests",
    "async-1k" => "Async1KTests",
    _ => "WorkloadTests"
  };

  private static void WriteSession(StreamWriter writer)
  {
    writer.WriteLine("public sealed class SessionToken : IAsyncDisposable");
    writer.WriteLine("{");
    writer.WriteLine("  public static int Created;");
    writer.WriteLine("  public int Id { get; }");
    writer.WriteLine();
    writer.WriteLine("  private SessionToken(int id) => Id = id;");
    writer.WriteLine();
    writer.WriteLine("  public static Task<SessionToken> CreateAsync()");
    writer.WriteLine("  {");
    writer.WriteLine("    int id = Interlocked.Increment(ref Created);");
    writer.WriteLine("    return Task.FromResult(new SessionToken(id));");
    writer.WriteLine("  }");
    writer.WriteLine();
    writer.WriteLine("  public ValueTask DisposeAsync() => ValueTask.CompletedTask;");
    writer.WriteLine("}");
    writer.WriteLine();
    writer.WriteLine("internal static class SessionRegistration");
    writer.WriteLine("{");
    writer.WriteLine("  [ModuleInitializer]");
    writer.WriteLine("  internal static void Register() => RegisterSessionFixture<SessionToken>();");
    writer.WriteLine("}");
    writer.WriteLine();
  }

  private static void WriteFixtureClass(StreamWriter writer, WorkloadSpec spec, int typeIndex)
  {
    string className = EmitText.FixtureClassName(typeIndex);
    writer.WriteLine("public sealed class " + className);
    writer.WriteLine("{");
    writer.WriteLine("  private static SessionToken? Token;");
    writer.WriteLine();
    writer.WriteLine("  [ModuleInitializer]");
    writer.WriteLine("  internal static void Register() => RegisterTests<" + className + ">();");
    writer.WriteLine();
    writer.WriteLine("  public static async Task SetupOnce()");
    writer.WriteLine("  {");
    writer.WriteLine("    Token = await SessionFixture.GetAsync<SessionToken>();");
    writer.WriteLine("  }");
    writer.WriteLine();
    writer.WriteLine("  public static Task CleanUpOnce()");
    writer.WriteLine("  {");
    writer.WriteLine("    Token = null;");
    writer.WriteLine("    return Task.CompletedTask;");
    writer.WriteLine("  }");
    writer.WriteLine();
    for (int methodIndex = 0; methodIndex < spec.MethodsPerClass; methodIndex++)
    {
      string name = EmitText.CaseName(methodIndex);
      writer.WriteLine("  public static Task " + name + "()");
      writer.WriteLine("  {");
      writer.WriteLine("    if (Token is null || Token.Id < 1)");
      writer.WriteLine("    {");
      writer.WriteLine("      throw new InvalidOperationException(\"session fixture was not created\");");
      writer.WriteLine("    }");
      writer.WriteLine();
      writer.WriteLine("    Bench.BenchProbe.Touch(Token.Id);");
      writer.WriteLine("    return Task.CompletedTask;");
      writer.WriteLine("  }");
      writer.WriteLine();
    }

    writer.WriteLine("}");
    writer.WriteLine();
  }

  private static void WriteMethod(StreamWriter writer, WorkloadSpec spec, int methodIndex)
  {
    string name = EmitText.CaseName(methodIndex);
    if (spec.Kind == WorkloadKind.Parameterized)
    {
      for (int input = 0; input < spec.Inputs; input++)
      {
        writer.WriteLine("  [Input(" + input.ToString(CultureInfo.InvariantCulture) + ")]");
      }

      writer.WriteLine("  public static Task " + name + "(int value)");
      writer.WriteLine("  {");
      writer.WriteLine("    Bench.BenchProbe.Touch(value);");
      writer.WriteLine("    return Task.CompletedTask;");
      writer.WriteLine("  }");
      writer.WriteLine();
      return;
    }

    if (spec.Kind == WorkloadKind.Async)
    {
      writer.WriteLine("  public static async Task " + name + "()");
      writer.WriteLine("  {");
      writer.WriteLine("    Bench.BenchProbe.Touch(0);");
      writer.WriteLine("    await Task.Yield();");
      writer.WriteLine("  }");
      writer.WriteLine();
      return;
    }

    writer.WriteLine("  public static Task " + name + "()");
    writer.WriteLine("  {");
    writer.WriteLine("    Bench.BenchProbe.Touch(0);");
    writer.WriteLine("    return Task.CompletedTask;");
    writer.WriteLine("  }");
    writer.WriteLine();
  }

  private static StreamWriter NewWriter(string path) => new(path, append: false);
}
