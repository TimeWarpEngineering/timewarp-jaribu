#region Purpose
// Shared names and the first-test probe emitted into every workload.
#endregion

#region Design
// Touch prints BENCH first once, from inside the first test body, so time-to-first-test
// is the same signal on every host. Report prints allocated bytes once on process exit.
// The probe type is internal so Fixie does not discover it as a test class.
#endregion

using System.Globalization;

internal static class EmitText
{
  internal static string CaseName(int index) =>
    "Case" + index.ToString(CultureInfo.InvariantCulture).PadLeft(5, '0');

  internal static string FixtureClassName(int index) =>
    "FixtureClass" + index.ToString(CultureInfo.InvariantCulture).PadLeft(3, '0');

  internal static void WriteProbe(string directory)
  {
    Directory.CreateDirectory(directory);
    string path = Path.Combine(directory, "bench-probe.g.cs");
    File.WriteAllText(path, Probe);
  }

  private const string Probe =
"""
// <auto-generated />
#nullable enable
using System.Globalization;
using System.Runtime.CompilerServices;

namespace Bench;

internal static class BenchProbe
{
  private static readonly long AllocatedAtStart = GC.GetTotalAllocatedBytes(true);
  private static int First;
  private static int Reported;
  internal static long Sink;

  [ModuleInitializer]
  internal static void Init()
  {
    AppDomain.CurrentDomain.ProcessExit += static (_, _) => Report();
  }

  internal static void Touch(int value)
  {
    Sink += value;
    if (Interlocked.Exchange(ref First, 1) != 0)
    {
      return;
    }

    Write("BENCH first");
    WriteFile("JARIBU_BENCH_SIGNAL", "BENCH first");
  }

  internal static void Report()
  {
    if (Interlocked.Exchange(ref Reported, 1) != 0)
    {
      return;
    }

    long allocated = GC.GetTotalAllocatedBytes(true) - AllocatedAtStart;
    string allocatedLine = "BENCH allocated_bytes=" + allocated.ToString(CultureInfo.InvariantCulture);
    Write(allocatedLine);
    WriteFile("JARIBU_BENCH_ALLOC", allocatedLine);
  }

  private static void Write(string line)
  {
    Console.WriteLine(line);
    Console.Out.Flush();
    Console.Error.WriteLine(line);
    Console.Error.Flush();
    byte[] bytes = System.Text.Encoding.UTF8.GetBytes(line + "\n");
    Stream stdout = Console.OpenStandardOutput();
    stdout.Write(bytes, 0, bytes.Length);
    stdout.Flush();
    Stream stderr = Console.OpenStandardError();
    stderr.Write(bytes, 0, bytes.Length);
    stderr.Flush();
  }

  private static void WriteFile(string variable, string line)
  {
    string? path = Environment.GetEnvironmentVariable(variable);
    if (string.IsNullOrEmpty(path))
    {
      return;
    }

    File.WriteAllText(path, line);
  }
}
""";
}
